"""Generate the deterministic sample e-commerce database used by the SQL exercises and the Playground.

    python datasets/generate_shop.py > datasets/shop.sql
"""
import random

rng = random.Random(20261006)

FIRST = ["Ana", "Ben", "Chen", "Dara", "Eli", "Fatima", "Goran", "Hana", "Ivan", "Jia", "Kofi", "Lena",
         "Mateo", "Nadia", "Omar", "Priya", "Quinn", "Rosa", "Sven", "Tara", "Uma", "Viktor", "Wei", "Yara"]
LAST = ["Silva", "Okafor", "Novak", "Haddad", "Kim", "Larsen", "Mehta", "Rossi", "Sato", "Weber", "Diaz", "Ng"]
COUNTRIES = ["US", "DE", "IN", "BR", "JP", "NG", "FR", "GB"]
PRODUCTS = [
    ("Mechanical Keyboard", "Electronics", 89.0), ("Noise-Cancelling Headphones", "Electronics", 199.0),
    ("USB-C Hub", "Electronics", 39.5), ("4K Monitor", "Electronics", 329.0),
    ("Standing Desk", "Furniture", 449.0), ("Ergonomic Chair", "Furniture", 289.0), ("Desk Lamp", "Furniture", 45.0),
    ("Python Crash Course", "Books", 32.0), ("Designing Data-Intensive Applications", "Books", 48.0),
    ("Deep Learning (Goodfellow)", "Books", 72.0), ("Coffee Beans 1kg", "Grocery", 24.0),
    ("Green Tea 100 bags", "Grocery", 12.5),
]
STATUSES = ["completed"] * 8 + ["cancelled", "pending"]


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return repr(v)


lines = [
    "-- Sample e-commerce database for Gradient (generated by datasets/generate_shop.py; do not edit by hand).",
    "PRAGMA foreign_keys = ON;",
    "CREATE TABLE customers (customer_id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, country TEXT NOT NULL, signup_date TEXT NOT NULL);",
    "CREATE TABLE products (product_id INTEGER PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL, price REAL NOT NULL CHECK (price > 0));",
    "CREATE TABLE orders (order_id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(customer_id), order_date TEXT NOT NULL, status TEXT NOT NULL CHECK (status IN ('completed','cancelled','pending')));",
    "CREATE TABLE order_items (order_id INTEGER NOT NULL REFERENCES orders(order_id), product_id INTEGER NOT NULL REFERENCES products(product_id), quantity INTEGER NOT NULL CHECK (quantity > 0), unit_price REAL NOT NULL, PRIMARY KEY (order_id, product_id));",
]

customers = []
for cid in range(1, 25):
    name = f"{FIRST[cid - 1]} {rng.choice(LAST)}"
    email = f"{FIRST[cid - 1].lower()}.{cid}@example.com"
    signup = f"2025-{rng.randint(1, 6):02d}-{rng.randint(1, 28):02d}"
    customers.append(cid)
    lines.append(f"INSERT INTO customers VALUES ({cid}, {q(name)}, {q(email)}, {q(rng.choice(COUNTRIES))}, {q(signup)});")

for pid, (name, cat, price) in enumerate(PRODUCTS, start=1):
    lines.append(f"INSERT INTO products VALUES ({pid}, {q(name)}, {q(cat)}, {price});")

# Four customers never order, so "customers without orders" has an answer.
buyers = customers[:-4]
oid = 0
for _ in range(90):
    oid += 1
    cust = rng.choice(buyers)
    date = f"2025-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"
    lines.append(f"INSERT INTO orders VALUES ({oid}, {cust}, {q(date)}, {q(rng.choice(STATUSES))});")
    for pid in rng.sample(range(1, len(PRODUCTS) + 1), rng.randint(1, 3)):
        base = PRODUCTS[pid - 1][2]
        unit = round(base * rng.choice([1.0, 1.0, 1.0, 0.9, 0.85]), 2)  # occasional discount
        lines.append(f"INSERT INTO order_items VALUES ({oid}, {pid}, {rng.randint(1, 4)}, {unit});")

print("\n".join(lines))
